DEFAULT_SYSTEM_PROMPT_NAME = "中间型"


def get_prompt_template(name: str) -> str | None:
    if not name:
        return None
    for tmpl_name, prompt in SYSTEM_PROMPT_TEMPLATES:
        if tmpl_name == name:
            return prompt
    return None
